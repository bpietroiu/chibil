#!/bin/bash
# Compile QuickJS (qjs interpreter) to MSIL with chibil, link to libc.
# Run under WSL: wsl bash /mnt/d/sandbox/chibil/targets/build/quickjs-chibil.sh
set -u
ROOT=/mnt/d/sandbox/chibil
source "$ROOT/targets/build/env.sh"
M=$ROOT/targets/musl-1.2.6
MUSLINC="-I$M/arch/x86_64 -I$M/arch/generic -I$M/obj/include -I$M/include"
SRC=$ROOT/targets/quickjs-2025-09-13
cd "$SRC" || exit 1

# -Iqjs-compat first: a stub <stdatomic.h> (musl ships none). Then quickjs dir + musl.
INCS="-I$ROOT/targets/build/qjs-compat -I. $MUSLINC"
# EMSCRIPTEN config: switch dispatch (no computed goto), no OS atomics, no stack-check
# (__builtin_frame_address), no malloc_usable_size — all the MSIL-incompatible bits off.
DEFS="-DEMSCRIPTEN -D_GNU_SOURCE -DCONFIG_VERSION=\"2025-09-13\""
CFLAGS="-c --target=coreclr -nostdinc -mlp64 -include $ROOT/targets/build/quickjs-chibil-compat.h $INCS $DEFS"

# repl.c is generated bytecode (qjsc_repl / qjsc_repl_size). Bootstrap it with a
# chibil-built qjsc so those symbols are DEFINED rather than unresolved imports.
bash "$ROOT/targets/build/qjs-gen-repl.sh" || exit 1

# The qjs interpreter's library + main TUs, including the generated REPL.
SRCS="cutils.c dtoa.c libregexp.c libunicode.c quickjs.c quickjs-libc.c qjs.c repl.c"

OBJDIR=/tmp/qjs_obj
mkdir -p "$OBJDIR"
ok=0; fail=0; objs=(); : > /tmp/qjs_failed.txt
for src in $SRCS; do
    obj="$OBJDIR/${src%.c}.obj"
    if $CH $CFLAGS "$src" -o "$obj" > "$obj.log" 2>&1; then
        ok=$((ok+1)); objs+=("$obj")
    else
        fail=$((fail+1)); echo "$src" >> /tmp/qjs_failed.txt
    fi
done

echo "=== compiled OK: $ok   FAILED: $fail ==="
if [ "$fail" -gt 0 ]; then
    echo "--- failed sources ---"; cat /tmp/qjs_failed.txt
    for s in $(cat /tmp/qjs_failed.txt); do echo "### $s ###"; tail -6 "$OBJDIR/${s%.c}.obj.log"; done
    exit 1
fi

echo "=== linking qjs.dll (chibil-link) ==="
$LINK -g -o qjs.dll -lc -lm "${objs[@]}" 2>&1 | tail -25
echo "link exit: ${PIPESTATUS[0]}"
ls -la qjs.dll 2>/dev/null
